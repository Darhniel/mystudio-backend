"""Write-side business logic for studios.

The HTTP layer validates shapes and permissions; this module owns the rules
that must also hold for management commands, admin actions and future workers.
Cloudinary calls live in :mod:`apps.common.cloudinary` so they can be reused by
the equipment app and mocked in tests.
"""

import logging

from django.core.exceptions import ValidationError
from django.db import IntegrityError, transaction
from django.db import models
from django.db.models import Max
from django.utils import timezone

from apps.common.cloudinary import (
    CloudinaryError,
    delete_image,
    upload_image,
)
from apps.common.constants import MAX_DATABASE_INTEGER
from apps.studios.models import Studio, StudioImage
from apps.studios.utils import is_slug_conflict

logger = logging.getLogger("mystudio.studios")
logger.addHandler(logging.NullHandler())

STUDIO_IMAGE_FOLDER = "mystudio/studios"


def create_studio(**data) -> Studio:
    """Create a studio from validated data.

    An omitted or blank slug is generated by ``Studio.save()``. Generated slugs
    are retried inside the model when concurrent requests collide; an explicit
    duplicate (including one created by a race after serializer validation) is
    converted into a field error instead of a ``500``.
    """

    try:
        with transaction.atomic():
            return Studio.objects.create(**data)
    except IntegrityError as exc:
        if is_slug_conflict(exc):
            raise ValidationError(
                {"slug": "This slug is already in use."}
            ) from exc
        raise


def update_studio(*, studio: Studio, **changes) -> Studio:
    """Apply validated changes to a studio and persist them."""

    if not changes:
        return studio

    for field, value in changes.items():
        setattr(studio, field, value)

    # A blank slug is regenerated inside ``Studio.save()``; include it in
    # ``update_fields`` so the generated value is actually written. Likewise,
    # ``updated_at`` only advances when it is part of ``update_fields``.
    fields = set(changes) | {"updated_at"}
    if "slug" in changes:
        fields.add("slug")

    try:
        studio.save(update_fields=list(fields))
    except IntegrityError as exc:
        if is_slug_conflict(exc):
            raise ValidationError(
                {"slug": "This slug is already in use."}
            ) from exc
        raise
    return studio


def deactivate_studio(*, studio: Studio) -> Studio:
    """Retire a studio without deleting its row or images."""

    if studio.is_active:
        studio.delete()
    return studio


def _next_display_order(studio) -> int:
    current = studio.images.aggregate(max_order=Max("display_order"))["max_order"]
    if current is None:
        return 0
    if current >= MAX_DATABASE_INTEGER:
        raise ValidationError(
            {"display_order": "No further display positions are available."}
        )
    return current + 1


def _discard_upload(public_id: str) -> None:
    """Best-effort cleanup when the database write after an upload fails.

    Any Cloudinary failure is swallowed here: the caller is already handling
    the original database error, which must remain the reported cause.
    """

    try:
        delete_image(public_id)
    except CloudinaryError:
        logger.warning(
            "Could not remove an uploaded studio image after a database error"
        )


def add_studio_image(
    *,
    studio,
    image,
    alt_text: str = "",
    display_order: int | None = None,
) -> StudioImage:
    """Upload a studio image and persist its Cloudinary references.

    The file reaches Cloudinary first; if the database insert then fails, the
    freshly uploaded asset is destroyed so PostgreSQL and Cloudinary stay in
    sync. When ``display_order`` is omitted the image is appended.
    """

    uploaded = upload_image(image, folder=STUDIO_IMAGE_FOLDER)

    if display_order is None:
        display_order = _next_display_order(studio)
        with transaction.atomic():
            StudioImage.objects.filter(
                studio=studio,
                display_order__gte=display_order,
            ).update(
                display_order=models.F("display_order") + 1,
                updated_at=timezone.now(),
            )

    try:
        with transaction.atomic():
            return StudioImage.objects.create(
                studio=studio,
                image_url=uploaded.url,
                cloudinary_public_id=uploaded.public_id,
                alt_text=alt_text or "",
                display_order=display_order,
            )
    except Exception:
        _discard_upload(uploaded.public_id)
        raise


def update_studio_image(
    *,
    image: StudioImage,
    alt_text: str | None = None,
    display_order: int | None = None,
) -> StudioImage:
    """Update the managed metadata of an existing studio image."""

    changes = {}
    if alt_text is not None:
        changes["alt_text"] = alt_text
    if display_order is not None:
        changes["display_order"] = display_order

    if not changes:
        return image

    for field, value in changes.items():
        setattr(image, field, value)
    # ``auto_now`` only runs for fields listed in ``update_fields``.
    image.save(update_fields=list(set(changes) | {"updated_at"}))
    return image


def delete_studio_image(*, image: StudioImage) -> None:
    """Delete the image row and its Cloudinary asset atomically.

    The row is deleted before the provider call inside the transaction, so a
    Cloudinary failure rolls the row deletion back. The image therefore stays
    visible and referenced. A provider outage returns ``502`` (or ``503`` when
    unconfigured) and changes nothing.
    """

    public_id = image.cloudinary_public_id

    with transaction.atomic():
        image.delete()
        delete_image(public_id)
